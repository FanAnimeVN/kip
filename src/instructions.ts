import fs from "node:fs";
import path from "node:path";
import { BIN_NAME, type AgentTarget, type KipConfig } from "./config.js";
import { activeDecisions, readDecisions, type Decision } from "./decisions.js";

export const START = "<!-- kip:start";
export const END = "<!-- kip:end -->";

/** Where each agent looks for project instructions. */
export const TARGET_FILES: Record<AgentTarget, string> = {
  agents: "AGENTS.md", // Codex, Cursor, Copilot agent, Zed, Amp, Jules, many others
  claude: "CLAUDE.md", // Claude Code
  gemini: "GEMINI.md", // Gemini CLI
  copilot: ".github/copilot-instructions.md", // GitHub Copilot
  cursor: ".cursor/rules/kip.mdc", // Cursor project rules
};

function decisionLine(d: Decision): string {
  const extra: string[] = [];
  if (d.use.length) extra.push(`use: ${d.use.join(", ")}`);
  if (d.avoid.length) extra.push(`avoid: ${d.avoid.join(", ")}`);
  const status = d.status === "proposed" ? " _(proposed)_" : "";
  const why = d.why ? ` — ${d.why}` : "";
  return `- **${d.title}**${status}${why}${extra.length ? ` (${extra.join(" · ")})` : ""}`;
}

/** The block every agent reads. Written in English for the agent, with a reply-language hint. */
export function instructionBlock(config: KipConfig, decisions: Decision[]): string {
  const cmd = config.command;
  const active = activeDecisions(decisions);
  const lines = [
    `${START} — generated by ${BIN_NAME}; edit .kip/decisions.md, then run \`${cmd} sync\` -->`,
    "## Team context (kip)",
    "",
    "Several people work in this repository, each possibly with a different AI coding agent. Keep everyone on the same page:",
    "",
    `1. **At the start of a session**, run \`${cmd} brief\` and tell the user, in a few bullets, what teammates changed and every ⚠ warning — before writing code.`,
    `2. **Before finishing a task or committing**, run \`${cmd} check\`. If it reports ⚠ divergence, stop and explain it to the user instead of working around it.`,
    `3. **Follow the team decisions below.** If a request contradicts one, say so, and suggest recording a new decision with \`${cmd} decide "<title>"\` once the team agrees.`,
    "",
    "### Team decisions (.kip/decisions.md)",
    "",
    ...(active.length ? active.map(decisionLine) : ["_No decisions recorded yet._"]),
  ];
  if (config.lang === "vi") lines.push("", "Reply to the user in Vietnamese.");
  lines.push(END);
  return lines.join("\n");
}

/** Insert or replace the kip block in a markdown file, leaving everything else untouched. */
export function upsertBlock(existing: string | null, block: string): string {
  if (existing === null || existing.trim() === "") return block + "\n";
  const start = existing.indexOf(START);
  const end = existing.indexOf(END, start === -1 ? 0 : start);
  if (start !== -1 && end !== -1) {
    return existing.slice(0, start) + block + existing.slice(end + END.length);
  }
  return existing.replace(/\s*$/, "") + "\n\n" + block + "\n";
}

export type WriteResult = "created" | "updated" | "unchanged";

function writeIfChanged(file: string, content: string): WriteResult {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === content) return "unchanged";
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return prev === null ? "created" : "updated";
}

export function hookCommand(config: KipConfig): string {
  return `${config.command} brief --hook`;
}

interface HookEntry {
  matcher?: string;
  hooks?: { type?: string; command?: string; timeout?: number }[];
}

/** Add a Claude Code SessionStart hook so Claude briefs the user automatically. Preserves other settings. */
export function upsertClaudeHook(root: string, config: KipConfig): WriteResult | "skipped" {
  const file = path.join(root, ".claude", "settings.json");
  let settings: Record<string, unknown> = {};
  if (fs.existsSync(file)) {
    try {
      settings = JSON.parse(fs.readFileSync(file, "utf8")) as Record<string, unknown>;
    } catch {
      return "skipped"; // never clobber a settings file we can't parse
    }
  }
  const hooks = (settings.hooks ?? {}) as Record<string, HookEntry[]>;
  const sessionStart = Array.isArray(hooks.SessionStart) ? hooks.SessionStart : [];
  const already = sessionStart.some((e) => e.hooks?.some((h) => h.command?.includes("brief --hook")));
  if (already) return "unchanged";
  sessionStart.push({ hooks: [{ type: "command", command: hookCommand(config), timeout: 30 }] });
  hooks.SessionStart = sessionStart;
  settings.hooks = hooks;
  return writeIfChanged(file, JSON.stringify(settings, null, 2) + "\n");
}

export interface SyncResult {
  file: string;
  result: WriteResult | "skipped";
}

/** Regenerate every agent instruction file from .kip/decisions.md. */
export function syncInstructions(root: string, config: KipConfig): SyncResult[] {
  const block = instructionBlock(config, readDecisions(root));
  const results: SyncResult[] = [];
  for (const target of config.agents) {
    const rel = TARGET_FILES[target];
    const file = path.join(root, rel);
    let content: string;
    if (target === "cursor") {
      // Cursor rule files are owned entirely by kip.
      content = `---\ndescription: Team context and decisions maintained by kip\nalwaysApply: true\n---\n\n${block}\n`;
    } else {
      const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
      content = upsertBlock(prev, block);
    }
    results.push({ file: rel, result: writeIfChanged(file, content) });
  }
  if (config.claudeHook && config.agents.includes("claude")) {
    results.push({ file: ".claude/settings.json", result: upsertClaudeHook(root, config) });
  }
  return results;
}
